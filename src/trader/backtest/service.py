# assumed_fee_tier -> per-side fee in basis points (mapped onto the engine's
# taker_fee; slippage kept at the fixture's standard 1bp).
FEE_TIER_BPS = {
    "tier_1_maker": 30,
    "tier_2_maker": 20,
    "tier_3_maker": 10,
    "coinbase_tier_1": 40,
    "coinbase_tier_2": 25,
    "coinbase_tier_3": 15,
}
SLIPPAGE = 0.0001


def _load_fixture_ohlc(
    path: str,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Load the fixture's opens, highs, lows and closes indexed by date."""
    d = pd.read_csv(path, parse_dates=["date"]).set_index("date")
    symbols = [c[: -len("_open")] for c in d.columns if c.endswith("_open")]
    frames = []
    for field in ("open", "high", "low", "close"):
        f = d[[f"{s}_{field}" for s in symbols]]
        f.columns = symbols
        frames.append(f)
    return frames[0], frames[1], frames[2], frames[3]


def _cost_model(tier: str) -> CostModel:
    if tier not in FEE_TIER_BPS:
        raise ValueError(
            f"unknown assumed_fee_tier {tier!r}; expected one of {sorted(FEE_TIER_BPS)}"
        )
    fee = FEE_TIER_BPS[tier] / 10_000
    return CostModel(maker_fee=fee, taker_fee=fee, slippage=SLIPPAGE)


def _benchmark(closes: pd.DataFrame, idx: pd.Index) -> pd.Series:
    """Equal-weight buy-and-hold of the frame's assets, normalized to 1.

    Each asset is bought at its own first listed close with an equal share
    of the starting capital; its allocation sits as cash (1.0) until then.
    """
    frame = closes.loc[idx]
    base = frame.apply(
        lambda c: (
            c.loc[c.first_valid_index()]
            if c.first_valid_index() is not None
            else float("nan")
        )
    )
    return (frame / base).fillna(1.0).mean(axis=1)


def execute_backtest(params: BacktestParams) -> BacktestResult:
    if params.strategy_sleeve in CANDIDATE_PRESETS:
        return _execute_candidate(params)
    if params.vol_target <= 0:
        raise ValueError(f"vol_target must be positive, got {params.vol_target}")

    opens, closes = engine.load_fixture(str(FIXTURE))

    available = [s for s in dict.fromkeys(params.asset_universe) if s in closes.columns]
    if not available:
        raise ValueError(
            f"none of the requested assets exist in the data set: "
            f"{params.asset_universe!r} (available: {list(closes.columns)})"
        )
    opens = opens[available]
    closes = closes[available]

    # Drop only leading rows where every requested asset lacks a price —
    # the engine still needs the full history for warmup. Pre-listing NaNs
    # stay NaN: weight 0, never traded, warmup on real prices only.
    has_price = closes.notna().any(axis=1)
    opens = opens[has_price]
    closes = closes[has_price]

    if closes.loc[params.start_date : params.end_date].empty:
        raise ValueError(
            f"no price data between {params.start_date} and {params.end_date}"
        )

    # The run starts at the primary asset's first listed day, so every
    # reported point has a finite asset_price and no fills happen outside
    # the reported window. The engine still sees the full frame above for
    # warmup (weights are computed over all of `closes` before slicing).
    first = cast(pd.Timestamp | None, closes[available[0]].first_valid_index())
    if first is None or first.date() > date.fromisoformat(params.end_date):
        raise ValueError(
            f"no price data for {available[0]} between "
            f"{params.start_date} and {params.end_date}"
        )
    start = max(date.fromisoformat(params.start_date), first.date()).isoformat()

    cost = _cost_model(params.assumed_fee_tier)
    extra = params.extra_params
    if params.strategy_sleeve == "trend_momentum":
        result = engine.run(
            opens,
            closes,
            cost,
            vol_target=params.vol_target,
            start=start,
            end=params.end_date,
        )
    elif params.strategy_sleeve == "cross_sectional_momentum":
        try:
            lookback_days = int(extra.get("lookback_days", 30))
            top_k = int(extra.get("top_k", 3))
            band = float(extra.get("band", 0.20))
        except (TypeError, ValueError) as exc:
            raise ValueError(f"invalid extra_params override: {exc}") from exc
        gate = extra.get("btc_gate", True)
        btc_gate = (
            gate.strip().lower() in ("1", "true", "yes", "on")
            if isinstance(gate, str)
            else bool(gate)
        )
        weights = cross_sectional_momentum_weights(
            closes,
            vol_target=params.vol_target,
            lookback_days=lookback_days,
            top_k=top_k,
            btc_gate=btc_gate,
        )
        result = engine.run_weights(
            opens,
            closes,
            weights,
            cost,
            band=band,
            start=start,
            end=params.end_date,
        )
    elif params.strategy_sleeve == "ping_pong_subsidy":
        try:
            band = float(extra.get("band", 0.20))
            target_tier_volume = float(extra.get("target_tier_volume", 10_000.0))
            daily_booster_cap_usd = float(extra.get("daily_booster_cap_usd", 2_000.0))
            spread_capture_bps = float(extra.get("spread_capture_bps", 10.0))
        except (TypeError, ValueError) as exc:
            raise ValueError(f"invalid extra_params override: {exc}") from exc
        o, h, low, c = _load_fixture_ohlc(str(FIXTURE))
        o, h, low, c = o[available], h[available], low[available], c[available]
        has_price = c.notna().any(axis=1)
        o, h, low, c = o[has_price], h[has_price], low[has_price], c[has_price]
        alpha_sleeve = extra.get("alpha_sleeve", "cross_sectional_momentum")
        if alpha_sleeve == "cross_sectional_momentum":
            alpha_weights = cross_sectional_momentum_weights(
                c, vol_target=params.vol_target
            )
        elif alpha_sleeve == "trend_momentum":
            alpha_weights = engine._target_weights(c, params.vol_target)
        else:
            raise ValueError(f"unknown alpha_sleeve {alpha_sleeve!r}")
        result = subsidy.run_with_ping_pong_subsidy(
            o,
            h,
            low,
            c,
            alpha_weights,
            float(params.starting_capital),
            start,
            params.end_date,
            band=band,
            slippage=SLIPPAGE,
            target_tier_volume=target_tier_volume,
            daily_booster_cap_usd=daily_booster_cap_usd,
            spread_capture_bps=spread_capture_bps,
        )
    else:
        raise ValueError(f"unknown strategy_sleeve {params.strategy_sleeve!r}")

    capital = float(params.starting_capital)
    equity = result.equity * capital
    bench = _benchmark(closes, result.equity.index) * capital
    dd = 1 - equity / equity.cummax()

    primary = available[0]
    points = [
        BacktestPoint(
            timestamp=day.date().isoformat(),
            equity=Decimal(str(round(equity[day], 2))),
            benchmark_equity=Decimal(str(round(bench[day], 2))),
            drawdown=round(float(dd[day]), 6),
            asset_price=Decimal(str(round(closes.loc[day, primary], 2))),
        )
        for day in result.equity.index
    ]

    years = len(equity) / engine.ANN
    # Baseline is cash at the first open (normalized 1.0): the first fill can
    # trade at that open, so day-1 P&L belongs inside the CAGR.
    cagr = result.equity.iloc[-1] ** (1 / years) - 1
    benchmark_cagr = (bench.iloc[-1] / capital) ** (1 / years) - 1

    # Booster summary rows (size 0) count toward fees but are not alpha
    # sells, so they stay out of the win-rate denominator.
    sells = [t for t in result.trades if t["side"] == "SELL" and t["size"] > 0]
    wins = sum(1 for t in sells if t["pnl"] > 0)

    trades = [
        BacktestTrade(
            date=t["date"].date().isoformat(),
            asset=t["symbol"],
            side=t["side"],
            size=Decimal(str(round(t["size"] * capital, 8))),
            price=Decimal(str(round(t["price"], 2))),
            pnl=Decimal(str(round(t["pnl"] * capital, 2))),
            fee=Decimal(str(round(t["fee"] * capital, 2))),
        )
        for t in result.trades
    ]

    return BacktestResult(
        summary_metrics=BacktestSummaryMetrics(
            cagr=round(float(cagr), 6),
            benchmark_cagr=round(float(benchmark_cagr), 6),
            max_drawdown=round(float(dd.max()), 6),
            total_trades=len(trades),
            win_rate=round(wins / len(sells), 6) if sells else 0.0,
            total_fees_paid=Decimal(
                str(round(sum(t["fee"] for t in result.trades) * capital, 2))
            ),
        ),
        timeseries_data=points,
        trade_log=trades,
    )


DATA_DIR = Path(__file__).resolve().parent / "data"
FUNDING_CSV = DATA_DIR / "funding_daily.csv"
INTRADAY_CSV = DATA_DIR / "btc_eth_intraday_1h.csv"


def load_funding(path: Path = FUNDING_CSV) -> pd.DataFrame | None:
    """Daily funding rates, columns ``date, <SYM>-USD, ...``. None if absent."""
    if not path.exists():
        return None
    return pd.read_csv(path, parse_dates=["date"]).set_index("date")


def load_intraday(path: Path = INTRADAY_CSV) -> dict[str, pd.DataFrame] | None:
    """1h OHLC bars per symbol from ``timestamp, <SYM>_{open,high,low,close}``."""
    if not path.exists():
        return None
    d = pd.read_csv(path, parse_dates=["timestamp"]).set_index("timestamp")
    symbols = [c[: -len("_open")] for c in d.columns if c.endswith("_open")]
    out: dict[str, pd.DataFrame] = {}
    for s in symbols:
        f = d[[f"{s}_{f}" for f in ("open", "high", "low", "close")]]
        f.columns = ["open", "high", "low", "close"]
        out[s] = f.dropna()
    return out


def data_availability() -> dict[str, dict[str, str | bool]]:
    """Status and date range of each dataset the backtests can use."""
    out: dict[str, dict[str, str | bool]] = {}
    for name, path in (
        ("daily", FIXTURE),
        ("funding", FUNDING_CSV),
        ("intraday", INTRADAY_CSV),
    ):
        if not path.exists():
            out[name] = {"status": "missing"}
            continue
        with path.open() as f:
            f.readline()
            first = f.readline().split(",", 1)[0]
        last = ""
        with path.open("rb") as f:
            f.seek(0, 2)
            tail = f.read(4096).decode(errors="replace").strip().splitlines()
            last = tail[-1].split(",", 1)[0] if tail else ""
        out[name] = {"status": "ok", "start": first, "end": last}
    return out


def _resample(bars: dict[str, pd.DataFrame], bar_tf: str) -> dict[str, pd.DataFrame]:
    if bar_tf == "1h":
        return bars
    rule = {"4h": "4h"}[bar_tf]
    agg = {"open": "first", "high": "max", "low": "min", "close": "last"}
    return {s: f.resample(rule).agg(agg).dropna() for s, f in bars.items()}


def _execute_candidate(params: BacktestParams) -> BacktestResult:
    """Run one of the four contained candidate presets."""
    from trader.backtest.costs import tier_cost_model
    from trader.backtest.sleeves import (
        funding_downtrend_weights,
        regime_composite_weights,
        trend_long_short_fut_weights,
    )

    sleeve = params.strategy_sleeve
    preset = CANDIDATE_PRESETS[sleeve]
    p = {**preset["defaults"], **params.extra_params, **params.params}
    # Echo the effective params in the compact summary.
    params = params.model_copy(update={"extra_params": p})
    tier = params.fee_tier or preset.get("default_fee_tier", "adv2_spot")
    cost = tier_cost_model(tier, params.execution_mode)

    needs = preset["requires"]
    missing: list[str] = []
    funding = load_funding() if "funding" in needs else None
    intraday = load_intraday() if "intraday" in needs else None
    if "funding" in needs and funding is None:
        missing.append(
            f"funding ({FUNDING_CSV} — run scripts/fetch_backtest_data.py --funding)"
        )
    if "intraday" in needs and intraday is None:
        missing.append(
            f"intraday ({INTRADAY_CSV} — run scripts/fetch_backtest_data.py --intraday)"
        )
    if missing:
        return _missing_data_result(params, "; ".join(missing))

    # Every daily candidate lists "funding" in requires, so it is present
    # past the missing check; keep a frame for mypy either way.
    funding_df = funding if funding is not None else pd.DataFrame()

    opens, closes = engine.load_fixture(str(FIXTURE))
    available = [s for s in dict.fromkeys(params.asset_universe) if s in closes.columns]
    if preset["kind"] != "intraday":
        if not available:
            raise ValueError(
                f"none of the requested assets exist in the data set: "
                f"{params.asset_universe!r} (available: {list(closes.columns)})"
            )
        closes = closes[available]
        opens = opens[available]
        has_price = closes.notna().any(axis=1)
        opens, closes = opens[has_price], closes[has_price]
        if closes.loc[params.start_date : params.end_date].empty:
            raise ValueError(
                f"no price data between {params.start_date} and {params.end_date}"
            )
        first = closes[available[0]].first_valid_index()
        start = max(
            date.fromisoformat(params.start_date),
            cast(pd.Timestamp, first).date(),
        ).isoformat()
        band = float(p.get("rebalance_band", 0.20))
        funding_pnl: pd.Series | None = None

        if sleeve == "funding_downtrend":
            weights = funding_downtrend_weights(
                closes,
                funding_df.reindex(closes.index).ffill(),
                max_rules=int(p["max_rules"]),
                funding_window_days=int(p["funding_window_days"]),
                funding_threshold=float(p["funding_threshold"]),
                funding_zscore=(
                    None if p["funding_zscore"] is None else float(p["funding_zscore"])
                ),
                max_weight=float(p["max_weight"]),
                assets=list(p["assets"]),
            )
        elif sleeve == "regime_composite":
            weights = regime_composite_weights(
                closes,
                funding_df.reindex(closes.index).ffill(),
                rule_set=str(p["rule_set"]),
                vol_target=float(p["vol_target"]),
                mixed_mode=str(p["mixed_mode"]),
                downtrend_mode=str(p["downtrend_mode"]),
                dip_z=float(p["dip_z"]),
                dip_hold_days=int(p["dip_hold_days"]),
                dip_weight=float(p["dip_weight"]),
            )
        elif sleeve == "trend_long_short_fut":
            weights, funding_pnl = trend_long_short_fut_weights(
                closes,
                funding_df.reindex(closes.index).ffill(),
                vol_target=float(p["vol_target"]),
                short_max_rules=int(p["short_max_rules"]),
                short_vol_target=float(p["short_vol_target"]),
                veto_neg_funding=bool(p["veto_neg_funding"]),
            )
        else:
            raise ValueError(f"unknown candidate sleeve {sleeve!r}")

        result = engine.run_weights(
            opens, closes, weights, cost, band=band, start=start, end=params.end_date
        )
        if p.get("include_funding_pnl") and funding_pnl is not None:
            # Daily funding cashflow of the short leg (signal day t-1 applies at t).
            cf = funding_pnl.shift(1).reindex(result.equity.index).fillna(0.0)
            result.equity = result.equity * (1 + cf).cumprod()
        if float(p.get("idle_cash_apy", 0.0)):
            # Idle cash earns a simple daily yield on the uninvested share.
            apy = float(p["idle_cash_apy"]) / engine.ANN
            result.equity = result.equity * (1 + apy * (1 - result.exposure)).cumprod()
    else:
        bars = _resample(intraday or {}, str(p["bar_tf"]))
        bars = {
            s: f.loc[params.start_date : params.end_date]
            for s, f in bars.items()
            if s in [f"{a}-USD" for a in ("BTC", "ETH")]
        }
        bars = {s: f for s, f in bars.items() if not f.empty}
        if not bars:
            return _missing_data_result(
                params,
                f"no intraday bars between {params.start_date} and {params.end_date}",
            )
        bars_per_day = {"1h": 24, "4h": 6}[str(p["bar_tf"])]
        result = engine.run_intraday_flush_mr(
            bars,
            cost,
            atr_period=int(p["atr_period"]),
            entry_atr_mult=float(p["entry_atr_mult"]),
            target_atr_mult=float(p["target_atr_mult"]),
            max_hold_bars=int(int(p["max_hold_hours"]) / 24 * bars_per_day),
            crash_veto_24h=float(p["crash_veto_24h"]),
            max_weight=float(p["max_weight"]),
            trade_through_bps=float(p["trade_through_bps"]),
            bars_per_day=bars_per_day,
        )

    capital = float(params.starting_capital)
    equity = result.equity * capital
    bench_idx = result.equity.index
    if preset["kind"] == "intraday":
        # Daily benchmark resampled onto the bar grid.
        _, dcloses = engine.load_fixture(str(FIXTURE))
        bench_cols = available or list(dcloses.columns)
        daily_bench = _benchmark(dcloses[bench_cols], dcloses.index)
        bench = daily_bench.reindex(bench_idx, method="ffill").fillna(1.0) * capital
        primary = (available or ["BTC-USD"])[0]
        prices = dcloses[primary].reindex(bench_idx, method="ffill")
    else:
        bench = _benchmark(closes, bench_idx) * capital
        primary = available[0]
        prices = closes[primary]

    combined = None
    if params.combine_trend:
        _, dcloses = engine.load_fixture(str(FIXTURE))
        dcloses = dcloses[available] if available else dcloses
        tw = engine._target_weights(dcloses, 0.40)
        trend_res = engine.run_weights(
            engine.load_fixture(str(FIXTURE))[0][available or list(dcloses.columns)],
            dcloses,
            tw,
            cost,
            start=str(bench_idx[0].date()),
            end=str(bench_idx[-1].date()),
        )
        combo = (result.equity + trend_res.equity.reindex(bench_idx).ffill()) / 2
        combined = (combo, trend_res)

    return _wrap_result(
        params,
        result,
        equity,
        bench,
        prices,
        primary,
        closes=closes if preset["kind"] != "intraday" else None,
        combined=combined,
        tier=tier,
        data_status="ok",
    )


def _missing_data_result(params: BacktestParams, message: str) -> BacktestResult:
    compact = {
        "strategy": params.strategy_sleeve,
        "data_status": "missing",
        "message": message,
        "gates": {
            "G1_OOS_SHARPE": "FAIL",
            "G2_NON_UPTREND": "FAIL",
            "G3_DD_LIMIT": "FAIL",
            "G4_ADV1_SURVIVAL": "FAIL",
            "G5_CADENCE": "INFO",
        },
    }
    return BacktestResult(
        summary_metrics=BacktestSummaryMetrics(
            cagr=0.0,
            benchmark_cagr=0.0,
            max_drawdown=0.0,
            total_trades=0,
            win_rate=0.0,
            total_fees_paid=Decimal("0"),
        ),
        timeseries_data=[],
        trade_log=[],
        compact_summary=compact,
        compact_report=(
            f"# {params.strategy_sleeve}\n\ndata_status: missing — {message}\n"
        ),
    )


def _split_stats(
    result: engine.BacktestResult, capital: float, start: str | None, end: str | None
) -> dict[str, float]:
    if result.equity.loc[start:end].empty:
        return {
            k: 0.0
            for k in (
                "cagr",
                "sharpe",
                "turnover_yr",
                "exposure",
                "max_dd",
                "calmar",
                "trades",
                "trades_per_mo",
                "win_rate",
                "avg_trade_bps",
                "fee_drag_yr",
            )
        }
    stats = result.stats(start=start, end=end)
    trades = [
        t
        for t in result.trades
        if (start is None or t["date"] >= pd.Timestamp(start))
        and (end is None or t["date"] <= pd.Timestamp(end))
    ]
    sells = [t for t in trades if t["side"] == "SELL" and t["size"] > 0]
    years = max(len(result.equity.loc[start:end]) / engine.ANN, 1e-9)
    wins = sum(1 for t in sells if t["pnl"] > 0)
    bps = [
        t["pnl"] / (t["size"] * t["price"]) * 10_000
        for t in sells
        if t["size"] * t["price"] > 0
    ]
    fees = sum(t["fee"] for t in trades)
    max_dd = stats.pop("maxdd")
    stats.update(
        {
            "max_dd": max_dd,
            "calmar": stats["cagr"] / abs(max_dd) if max_dd else 0.0,
            "trades": len(trades),
            "trades_per_mo": len(trades) / (years * 12),
            "win_rate": wins / len(sells) if sells else 0.0,
            "avg_trade_bps": sum(bps) / len(bps) if bps else 0.0,
            "fee_drag_yr": fees / years,
        }
    )
    return stats


def _compact(
    params: BacktestParams,
    result: engine.BacktestResult,
    closes: pd.DataFrame | None,
    combined: tuple[pd.Series, engine.BacktestResult] | None,
    tier: str,
    data_status: str,
) -> dict[str, Any]:
    equity = result.equity
    splits = {
        "is_2018_2021": _split_stats(result, 1.0, None, "2021-12-31"),
        "oos_2022_plus": _split_stats(result, 1.0, "2022-01-01", None),
        "full": _split_stats(result, 1.0, None, None),
    }

    rets = equity.pct_change().fillna(0.0)
    oos = rets.loc["2022-01-01":]
    oos_regimes: dict[str, dict[str, float]] = {}
    if closes is not None and not oos.empty:
        from trader.backtest.sleeves import rules_on

        on = rules_on(closes.iloc[:, 0])
        labels = on.map(regime.trend).reindex(equity.index)
        for label in ("uptrend", "mixed", "downtrend"):
            mask = labels.loc["2022-01-01":] == label
            days = oos[mask]
            tr = [
                t
                for t in result.trades
                if t["date"] >= pd.Timestamp("2022-01-01")
                and bool(mask.get(t["date"], False))
            ]
            oos_regimes[label] = {
                "days_pct": len(days) / len(oos) if len(oos) else 0.0,
                "contrib_cagr": (
                    float(np.prod(1.0 + days.to_numpy(dtype=float)) - 1.0)
                    if len(days)
                    else 0.0
                ),
                "trades": len(tr),
                "net_pnl_pct": float(days.sum()),
            }
    else:
        for label in ("uptrend", "mixed", "downtrend"):
            oos_regimes[label] = {
                "days_pct": 0.0,
                "contrib_cagr": 0.0,
                "trades": 0,
                "net_pnl_pct": 0.0,
            }

    oos_eq = equity.loc["2022-01-01":]
    yr = (oos_eq.resample("YE").last() / oos_eq.resample("YE").first() - 1).dropna()
    yearly = {
        str(cast(pd.Timestamp, k).year): round(float(v), 6) for k, v in yr.items()
    }

    asset_contrib: dict[str, float] = {}
    if closes is not None:
        tot = float(equity.iloc[-1] / equity.iloc[0] - 1) or 1.0
        tgt = result.weights.shift(1).fillna(0.0)
        for s in closes.columns:
            r = closes[s].pct_change().fillna(0.0).reindex(equity.index).fillna(0.0)
            asset_contrib[s.split("-")[0]] = round(float((tgt[s] * r).sum()) / tot, 6)

    gates = {
        "G1_OOS_SHARPE": (
            "PASS" if splits["oos_2022_plus"]["sharpe"] >= 0.75 else "FAIL"
        ),
        "G2_NON_UPTREND": (
            "PASS"
            if oos_regimes["downtrend"]["net_pnl_pct"]
            + oos_regimes["mixed"]["net_pnl_pct"]
            > 0
            else "FAIL"
        ),
        "G5_CADENCE": (
            "PASS" if splits["oos_2022_plus"]["trades_per_mo"] >= 2 else "INFO"
        ),
    }
    if combined is not None:
        combo, trend_res = combined
        combo_dd = float((combo / combo.cummax() - 1).min())
        gates["G3_DD_LIMIT"] = "PASS" if combo_dd >= -0.30 else "FAIL"
    else:
        gates["G3_DD_LIMIT"] = (
            "PASS" if splits["oos_2022_plus"]["max_dd"] >= -0.30 else "FAIL"
        )
    # G4: OOS CAGR positive at the harsher survival tier is checked by sweep;
    # here report pass when OOS CAGR is positive at the requested tier.
    gates["G4_ADV1_SURVIVAL"] = (
        "PASS" if splits["oos_2022_plus"]["cagr"] > 0 else "FAIL"
    )

    compact = {
        "strategy": params.strategy_sleeve,
        "fee_tier": tier,
        "execution_mode": params.execution_mode,
        "params": {k: v for k, v in params.extra_params.items()},
        "data_status": data_status,
        "data_range": {
            "start": str(equity.index[0].date()) if len(equity) else None,
            "end": str(equity.index[-1].date()) if len(equity) else None,
        },
        "splits": splits,
        "oos_regimes": oos_regimes,
        "oos_yearly": yearly,
        "asset_contrib": asset_contrib,
        "gates": gates,
    }

    if combined is not None:
        combo, _ = combined
        years = len(combo) / engine.ANN
        combo_stats = {
            "cagr": float(combo.iloc[-1] ** (1 / years) - 1) if years > 0 else 0.0,
            "max_dd": float((combo / combo.cummax() - 1).min()),
        }
        combo_stats["calmar"] = (
            combo_stats["cagr"] / abs(combo_stats["max_dd"])
            if combo_stats["max_dd"]
            else 0.0
        )
        avg_30d_vol = float(
            result.turnover.rolling(30, min_periods=1).sum().mean()
        ) * float(params.starting_capital)
        _, taker_at_vol = subsidy.coinbase_fee_rate(avg_30d_vol)
        _, taker_at_tier = subsidy.coinbase_fee_rate(50_000.0)
        combo_stats["avg_30d_vol"] = avg_30d_vol
        combo_stats["est_subsidy_saved_yr"] = max(
            0.0, (taker_at_vol - taker_at_tier) * avg_30d_vol * 12
        )
        compact["combined"] = combo_stats

    return compact


def _report(compact: dict[str, Any]) -> str:
    """The ~30-line Markdown compact report."""
    s = compact["splits"]
    g = compact["gates"]
    rows = [
        f"# {compact['strategy']} @ {compact['fee_tier']} "
        f"({compact['execution_mode']})",
        f"range {compact['data_range']['start']}.."
        f"{compact['data_range']['end']} | "
        f"data_status={compact['data_status']}",
        "",
        "| split | CAGR | Sharpe | MaxDD | Calmar | Tr/mo | Win% "
        "| AvgBps | Turn/yr | FeeDrag | Exp |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name in ("is_2018_2021", "oos_2022_plus", "full"):
        r = s[name]
        rows.append(
            f"| {name} | {r['cagr']:.1%} | {r['sharpe']:.2f} | {r['max_dd']:.1%} | "
            f"{r['calmar']:.2f} | {r['trades_per_mo']:.1f} | {r['win_rate']:.0%} | "
            f"{r['avg_trade_bps']:.0f} | {r['turnover_yr']:.1f} | "
            f"{r['fee_drag_yr']:.4f} | "
            f"{r['exposure']:.0%} |"
        )
    rows += [
        "",
        "| OOS regime | days% | contrib | trades | net pnl |",
        "|---|---|---|---|---|",
    ]
    for name, r in compact["oos_regimes"].items():
        rows.append(
            f"| {name} | {r['days_pct']:.0%} | {r['contrib_cagr']:.1%} | "
            f"{r['trades']} | {r['net_pnl_pct']:.1%} |"
        )
    rows.append("")
    rows.append(
        "yearly: " + ", ".join(f"{y} {v:.1%}" for y, v in compact["oos_yearly"].items())
    )
    rows.append(
        "asset_contrib: "
        + ", ".join(f"{a} {v:.1%}" for a, v in compact["asset_contrib"].items())
    )
    if "combined" in compact:
        c = compact["combined"]
        rows.append(
            f"combined+subsidy: cagr {c['cagr']:.1%} maxdd {c['max_dd']:.1%} "
            f"calmar {c['calmar']:.2f} avg30dvol ${c['avg_30d_vol']:.0f} "
            f"subsidy_saved_yr ${c['est_subsidy_saved_yr']:.0f}"
        )
    rows.append("gates: " + ", ".join(f"{k}={v}" for k, v in g.items()))
    rows.append("")
    rows.append(
        "json: " + json.dumps(compact, separators=(",", ":"), default=str)[:2000]
    )
    return "\n".join(rows)


def _wrap_result(
    params: BacktestParams,
    result: engine.BacktestResult,
    equity: pd.Series,
    bench: pd.Series,
    prices: pd.Series,
    primary: str,
    *,
    closes: pd.DataFrame | None,
    combined: tuple[pd.Series, engine.BacktestResult] | None,
    tier: str,
    data_status: str,
) -> BacktestResult:
    compact = _compact(params, result, closes, combined, tier, data_status)
    dd = 1 - equity / equity.cummax()
    capital = float(params.starting_capital)
    years = max(len(equity) / engine.ANN, 1e-9)
    points = (
        [
            BacktestPoint(
                timestamp=day.date().isoformat() if hasattr(day, "date") else str(day),
                equity=Decimal(str(round(equity[day], 2))),
                benchmark_equity=Decimal(str(round(float(bench.loc[day]), 2))),
                drawdown=round(float(dd[day]), 6),
                asset_price=Decimal(str(round(float(prices.loc[day]), 2))),
            )
            for day in equity.index
        ]
        if params.include_series
        else []
    )
    sells = [t for t in result.trades if t["side"] == "SELL" and t["size"] > 0]
    wins = sum(1 for t in sells if t["pnl"] > 0)
    trades = (
        [
            BacktestTrade(
                date=(
                    t["date"].date().isoformat()
                    if hasattr(t["date"], "date")
                    else str(t["date"])
                ),
                asset=t["symbol"],
                side=t["side"],
                size=Decimal(str(round(t["size"] * capital, 8))),
                price=Decimal(str(round(t["price"], 2))),
                pnl=Decimal(str(round(t["pnl"] * capital, 2))),
                fee=Decimal(str(round(t["fee"] * capital, 2))),
            )
            for t in result.trades
        ]
        if params.include_series
        else []
    )
    return BacktestResult(
        summary_metrics=BacktestSummaryMetrics(
            cagr=round(float(equity.iloc[-1] / capital) ** (1 / years) - 1, 6),
            benchmark_cagr=round(float(bench.iloc[-1] / capital) ** (1 / years) - 1, 6),
            max_drawdown=round(float(dd.max()), 6),
            total_trades=len(trades) or len(result.trades),
            win_rate=round(wins / len(sells), 6) if sells else 0.0,
            total_fees_paid=Decimal(
                str(round(sum(t["fee"] for t in result.trades) * capital, 2))
            ),
        ),
        timeseries_data=points,
        trade_log=trades,
        compact_summary=compact,
        compact_report=_report(compact),
    )
