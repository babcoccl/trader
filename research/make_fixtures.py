"""Regenerate research/fixtures/ from the full research data. Needs data/ built by the fetch scripts (see README.md)."""
import json, numpy as np, pandas as pd, warnings; warnings.filterwarnings("ignore")
import bt
BE = ["BTCUSDT", "ETHUSDT"]; NM = {"BTCUSDT": "BTC-USD", "ETHUSDT": "ETH-USD"}
O = bt.O[BE].loc[:"2026-11-19"]; C = bt.C[BE].loc[:"2026-11-19"]
d = pd.DataFrame({"date": C.index.strftime("%Y-%m-%d")})
for s in BE:
    d[f"{NM[s]}_open"] = O[s].values; d[f"{NM[s]}_close"] = C[s].values
d.to_csv("fixtures/btc_eth_daily.csv", index=False)
ren = {"sma50": "sma50", "sma100": "sma100", "sma200": "sma200", "mom30": "momentum30", "mom90": "momentum90", "mom180": "momentum180", "don20": "breakout20", "don55": "breakout55", "don100": "breakout100"}
w = bt.target_weights("ensemble", fixed=BE, cap=1.0, vol_target=0.4)
vol = bt._r.ewm(span=30, min_periods=20).std() * np.sqrt(365)
rows = []
for s in BE:
    x = pd.DataFrame({"date": C.index.strftime("%Y-%m-%d"), "symbol": NM[s]})
    for k, v in ren.items(): x[v] = bt.signal(k)[s].reindex(C.index).values
    x["ensemble"] = bt.signal("ensemble")[s].reindex(C.index).values; x["annual_vol"] = vol[s].reindex(C.index).values; x["target_weight"] = w[s].reindex(C.index).values
    rows.append(x)
pd.concat(rows).to_csv("fixtures/expected_signals.csv", index=False, float_format="%.12g")
exp = {"note": "Generated by research/make_fixtures.py from research/bt.py. Weights: ensemble, BTC+ETH, vol_target 0.40. Period 2018-04-01 to 2026-11-19. Stats as in bt.stats (years = rows/365).", "runs": {}}
for cname, (fee, slip) in {"study_040": (0.004, 0.0005), "bitstamp": (0.004, 0.0001)}.items():
    for band in (0.0, 0.1, 0.2, 0.3):
        r = bt.run(w, fee=fee, slip=slip, band=band); f = bt.stats(r); h = bt.stats(r, "2022-01-01")
        exp["runs"][f"{cname}_band_{band}"] = {"taker_fee": fee, "slippage": slip, "band": band, "full": {k: float(f[k]) for k in ("cagr", "maxdd", "sharpe", "turnover_yr", "exposure")}, "from_2022": {k: float(h[k]) for k in ("cagr", "maxdd", "sharpe")}, "final_equity": float(r.equity.iloc[-1])}
        if cname == "study_040" and band == 0.2: r[["equity", "turnover", "cost", "exposure"]].to_csv("fixtures/expected_equity_study_040_band_0.2.csv", float_format="%.12g", index_label="date")
json.dump(exp, open("fixtures/expected_backtest.json", "w"), indent=1)
